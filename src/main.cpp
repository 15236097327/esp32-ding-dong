bool lastState = false;

void drawEmojiScreen();
void drawIdleScreen();

void setup() {
  Serial.begin(115200);
  pinMode(IR_PIN, INPUT);
  pinMode(BUZZ_PIN, OUTPUT);
  digitalWrite(BUZZ_PIN, LOW);

  if (!display.begin(SSD1306_SWITCHCAPVCC, OLED_ADDRESS)) {
    Serial.println("OLED 失败！");
    while (1) { delay(1000); }
  }

  // 显示启动画面
  display.clearDisplay();
  display.setTextSize(2);
  display.setTextColor(SSD1306_WHITE);
  display.setCursor(20, 10);
  display.println("DOORBELL");
  display.setTextSize(1);
  display.setCursor(35, 40);
  display.println("Ready...");
  display.display();
  delay(1500);

  // 初始状态 = 没人
  lastState = false;
  drawIdleScreen();
  Serial.println("=== 门铃就绪 ===");
}

void loop() {
  bool someone = (digitalRead(IR_PIN) == LOW);

  if (someone != lastState) {
    lastState = someone;
    if (someone) {
      drawEmojiScreen();   // 有人 → 表情包
    } else {
      drawIdleScreen();    // 没人 → 等待
    }
  }

  if (someone) {
    digitalWrite(BUZZ_PIN, HIGH);
    delay(150);
    digitalWrite(BUZZ_PIN, LOW);
    delay(80);
  } else {
    digitalWrite(BUZZ_PIN, LOW);
    delay(50);
  }
}

// === 显示表情包 ===
void drawEmojiScreen() {
  display.clearDisplay();
  display.drawBitmap(0, 0, my_emoji, 128, 64, SSD1306_WHITE);
  display.display();
  Serial.println("叮咚！表情包登场！");
}

// === 等待画面 ===
void drawIdleScreen() {
  display.clearDisplay();
  display.setTextSize(2);
  display.setTextColor(SSD1306_WHITE);
  display.setCursor(35, 15);
  display.println("  _ ");
  display.setCursor(35, 30);
  display.println(" ( )");
  display.setCursor(35, 45);
  display.println("(_\"_)");

  display.setTextSize(1);
  display.setCursor(20, 57);
  display.println("Waiting...");

  display.display();
}
